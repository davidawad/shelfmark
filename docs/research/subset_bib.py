#!/usr/bin/env python3
"""Write each paper's references.bib as the cited subset of docs/research/references.bib.

The canonical file holds every entry once, with a `% verified:` comment block
above it. Each paper gets the entries it cites, in canonical order, comments
included, so the three bibliographies cannot drift apart.

Usage, from the repository root:

    python3 docs/research/subset_bib.py          # rewrite the three paper bibs
    python3 docs/research/subset_bib.py --check  # exit 1 if any is stale or a key is missing
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CANON = ROOT / "docs" / "research" / "references.bib"

# paper directory -> source files whose citations count
PAPERS = {
    "paper/paper1": ["paper.md"],
    "paper/paper2": ["paper.src.md"],
    "paper/method-survey": ["main.typ", "sections/*.typ"],
}

# Typst reference prefixes that are labels, not citations (@sec:intro, @tab:nav, ...)
TYPST_LABELS = {"sec", "tab", "eq", "fig"}

HEADER = """\
% References for {paper} (DRAFT).
%
% GENERATED by docs/research/subset_bib.py from docs/research/references.bib:
% the entries this paper cites, with their verification comments. Edit the
% canonical file and rerun the script; do not edit this file by hand.
"""


def entries(text):
    """Yield (key, block) for each entry, block including the comments above it."""
    pending = []
    lines = text.splitlines()
    i = 0
    out = []
    while i < len(lines):
        line = lines[i]
        m = re.match(r"@\w+\{([^,]+),", line)
        if m:
            block = pending + [line]
            i += 1
            while i < len(lines) and lines[i] != "}":
                block.append(lines[i])
                i += 1
            block.append("}")
            out.append((m.group(1), "\n".join(block)))
            pending = []
        elif line.startswith("% verified") or (pending and line.startswith("% ")):
            pending.append(line)
        else:
            pending = []
        i += 1
    return out


def cited(paper_dir, patterns):
    keys = set()
    for pat in patterns:
        for path in sorted((ROOT / paper_dir).glob(pat)):
            text = path.read_text()
            if path.suffix == ".md":
                # pandoc citations live inside [...]: [@a; @b] or [@a]
                for group in re.findall(r"\[([^\]]*@[^\]]*)\]", text):
                    keys.update(re.findall(r"(?<![\w.])@([A-Za-z][\w-]*)", group))
            else:
                for key, colon in re.findall(r"(?<![\w.])@([A-Za-z][\w-]*)(:?)", text):
                    if not colon:
                        keys.add(key)
    return keys - TYPST_LABELS


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if a paper bib is stale")
    args = ap.parse_args()

    canon = entries(CANON.read_text())
    known = {k for k, _ in canon}
    if len(known) != len(canon):
        sys.exit("subset_bib: duplicate key in references.bib")
    status = 0
    for paper_dir, patterns in PAPERS.items():
        keys = cited(paper_dir, patterns)
        missing = sorted(keys - known)
        if missing:
            print(f"subset_bib: {paper_dir} cites unknown keys: {', '.join(missing)}")
            status = 1
            continue
        body = "\n\n".join(block for k, block in canon if k in keys)
        text = HEADER.format(paper=paper_dir) + "\n" + body + "\n"
        target = ROOT / paper_dir / "references.bib"
        if args.check:
            if not target.exists() or target.read_text() != text:
                print(f"subset_bib: {target.relative_to(ROOT)} is stale")
                status = 1
        else:
            target.write_text(text)
            print(f"subset_bib: {target.relative_to(ROOT)}: {len(keys)} entries")
    return status


if __name__ == "__main__":
    sys.exit(main())
