#!/usr/bin/env python3
"""Generate ../generated.typ from the committed benchmark result files.

Reads only files that are committed in this repository; nothing is fetched,
no git ref other than the working tree is consulted, and no benchmark is run.
Every number in the paper's tables and every headline value (the `v`
dictionary in generated.typ) is produced here, so the numbers trace to the
result files named in SOURCES below and in paper/common/extra_results.py.

Usage, from the repository root:
    python3 paper/method-survey/scripts/gen_tables.py           # rewrite generated.typ
    python3 paper/method-survey/scripts/gen_tables.py --check   # exit 1 if it is stale
"""
import argparse
import contextlib
import importlib.util
import io
import json
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "paper/method-survey/generated.typ"

# role -> results directory (relative to the repository root)
SOURCES = {
    "r1": "bench/results/2026-10-10",
    "r2": "bench/results/2026-10-10-r2",
    "r3": "bench/results/2026-10-10-r3",
    "learned": "bench/results/2026-10-10-learned",
}
SCHEMES = ["acm-ccs", "arxiv", "bk", "eurovoc", "fdc", "ilc2", "ipc", "jel",
           "lcc", "lcc-full", "msc", "openalex-topics", "unesco-thesaurus"]


def show(role, name):
    return (ROOT / SOURCES[role] / name).read_text(encoding="utf-8")


def jload(role, name):
    return json.loads(show(role, name))


def pct(x, nd=1):
    from decimal import Decimal, ROUND_HALF_UP
    p = Decimal(repr(float(x))) * 100
    if 0 < p < Decimal("0.1"):
        nd = 2
    q = Decimal(1).scaleb(-nd)
    return f"{p.quantize(q, rounding=ROUND_HALF_UP)}%"


def dec(x, nd):
    """Round half up on the decimal text of x (markdown values are already 4 dp)."""
    from decimal import Decimal, ROUND_HALF_UP
    return str(Decimal(str(x)).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP))


def f3(x):
    return f"{x:.3f}"


def sdiff(d):
    t = f"{abs(d):.3f}"
    if t == "0.000":
        return "0.000"
    return ("+" if d > 0 else "\u2212") + t


def f2(x):
    return f"{x:.2f}"


def f1(x):
    return f"{x:.1f}"


def tstr(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def tup(cells):
    return "(" + ", ".join(tstr(c) for c in cells) + ",)"


def emit_rows(name, rows):
    print(f"#let {name} = (")
    for r in rows:
        print("  " + tup(r) + ",")
    print(")")
    print()


def full_row(j):
    s = j["structure"]
    return [j["scheme"], pct(j["coverage"]), f3(j["cost_norm"]),
            f3(j["revenue_norm"]), f3(j["skill"]),
            f1(s["effective_classes"]), f2(s["mean_depth"]), str(s["max_depth"]),
            str(s["max_branching"]), f3(s["gini"]), f1(s["nav_log_a1"])]


def md_table(text, start, end=None):
    """Rows of the first markdown table after `start` (cells stripped of ticks)."""
    a = text.index(start)
    lines = text[a:].splitlines()
    out, seen = [], False
    for l in lines[1:]:
        if l.startswith("|"):
            seen = True
            if re.match(r"^\|[ \-:|]+\|$", l):
                continue
            out.append([c.strip().strip("`") for c in l.strip().strip("|").split("|")])
        elif seen:
            break
    return out[1:]  # drop header


def rank(v):
    s = sorted(range(len(v)), key=lambda i: v[i])
    r = [0.0] * len(v)
    i = 0
    while i < len(s):
        j = i
        while j + 1 < len(s) and v[s[j + 1]] == v[s[i]]:
            j += 1
        for k in range(i, j + 1):
            r[s[k]] = (i + j) / 2 + 1
        i = j + 1
    return r


def pearson(x, y):
    n = len(x)
    mx, my = sum(x) / n, sum(y) / n
    num = sum((a - mx) * (b - my) for a, b in zip(x, y))
    den = math.sqrt(sum((a - mx) ** 2 for a in x) * sum((b - my) ** 2 for b in y))
    return num / den


def kendall_b(x, y):
    n = len(x)
    c = d = tx = ty = 0
    for i in range(n):
        for j in range(i + 1, n):
            p, q = x[i] - x[j], y[i] - y[j]
            if p == 0 and q == 0:
                continue
            if p == 0:
                tx += 1
            elif q == 0:
                ty += 1
            elif p * q > 0:
                c += 1
            else:
                d += 1
    return (c - d) / math.sqrt((c + d + tx) * (c + d + ty))


def main():
    print("// GENERATED by scripts/gen_tables.py from the committed result files.")
    print("// Do not edit by hand. Sources (paths in this repository):")
    for role, d in SOURCES.items():
        print(f"//   {role}: {d}/")
    print("//   shared: paper/common/extra_results.py and the sources it names")
    print("//   corpus facts: values of paper/paper1/scripts/make_tables.py")
    print()

    V = {}

    # ---- gold (r1 for arxiv/jel/lcc/lcc-full, r3 for corrected msc) ----
    g_arxiv = jload("r1", "arxiv-gold.json")
    g_jel = jload("r1", "jel-gold.json")
    g_lcc = jload("r1", "lcc-gold.json")
    g_lccfull = jload("r1", "lcc-full-gold.json")
    g_msc = jload("r3", "msc-gold.json")
    g_msc_old = jload("r1", "msc-gold.json")
    emit_rows("gold-corpus", [full_row(g_arxiv), full_row(g_msc), full_row(g_jel)])
    emit_rows("gold-holdout", [full_row(g_lccfull), full_row(g_lcc)])
    V["gold_arxiv_skill"] = f3(g_arxiv["skill"])
    V["gold_arxiv_cost"] = f3(g_arxiv["cost_norm"])
    V["gold_lcc_skill"] = f3(g_lcc["skill"])
    V["gold_lccfull_skill"] = f3(g_lccfull["skill"])
    V["gold_lcc_cost"] = f3(g_lcc["cost_norm"])
    V["gold_lccfull_cost"] = f3(g_lccfull["cost_norm"])
    V["gold_lcc_cov"] = pct(g_lcc["coverage"])
    V["gold_lcc_eff"] = f"{g_lcc['structure']['effective_classes']:.0f}"
    V["gold_lccfull_eff"] = f"{g_lccfull['structure']['effective_classes']:.0f}"
    V["gold_lcc_depth"] = f2(g_lcc["structure"]["mean_depth"])
    V["gold_lccfull_depth"] = f2(g_lccfull["structure"]["mean_depth"])
    V["gold_msc_cov"] = pct(g_msc["coverage"])
    V["gold_msc_cov_r1"] = pct(g_msc_old["coverage"])
    V["gold_msc_skill"] = f"{g_msc['skill']:.4f}"
    V["gold_msc_skill_r1"] = f"{g_msc_old['skill']:.4f}"
    V["gold_jel_cov"] = pct(g_jel["coverage"])

    # ---- placed (r2) ----
    placed = {s: jload("r2", f"{s}-placed.json") for s in SCHEMES}
    order = sorted(SCHEMES, key=lambda s: placed[s]["cost_norm"])
    emit_rows("placed-corpus", [full_row(placed[s]) for s in order])
    ph = {}
    for s in SCHEMES:
        try:
            ph[s] = jload("r2", f"{s}-placed-holdout.json")
        except FileNotFoundError:
            pass
    order_h = sorted(ph, key=lambda s: ph[s]["cost_norm"])
    emit_rows("placed-holdout", [full_row(ph[s]) for s in order_h])
    best, worst = order[0], order[-1]
    V["placed_best"], V["placed_best_skill"] = best, f3(placed[best]["skill"])
    V["placed_second"], V["placed_second_skill"] = order[1], f3(placed[order[1]]["skill"])
    V["placed_worst"], V["placed_worst_skill"] = worst, f3(placed[worst]["skill"])
    V["placed_arxiv_skill"] = f3(placed["arxiv"]["skill"])
    V["placed_arxiv_cov"] = pct(placed["arxiv"]["coverage"])
    V["placed_lcc_holdout_skill"] = f3(ph["lcc"]["skill"])
    V["placed_lccfull_holdout_skill"] = f3(ph["lcc-full"]["skill"])
    V["placed_bk_holdout_cov"] = pct(ph["bk"]["coverage"])
    V["placed_lccfull_holdout_cov"] = pct(ph["lcc-full"]["coverage"])
    covs = [placed[s]["coverage"] for s in SCHEMES]
    sks = [placed[s]["skill"] for s in SCHEMES]
    V["rho"] = f2(pearson(rank(covs), rank(sks)))
    hi = [s for s in SCHEMES if placed[s]["coverage"] >= 0.95]
    V["n_highcov"] = str(len(hi))
    V["highcov_min"] = f3(min(placed[s]["skill"] for s in hi))
    V["highcov_max"] = f3(max(placed[s]["skill"] for s in hi))
    V["ref_corpus"] = f3(placed["arxiv"]["ref_cost_norm"])
    V["ref_holdout"] = f3(ph["lcc"]["ref_cost_norm"])
    V["lccfull_navscan"] = f"{placed['lcc-full']['structure']['nav_scan']:.0f}"

    # ---- placement statistics (r1 and r2 markdown tables) ----
    pc2 = md_table(show("r2", "results.md"), "Placement counts")
    pc1 = md_table(show("r1", "results.md"), "Placement counts")
    rows = []
    for r in pc2:
        sch, corp, pl, fl, fb, _failed, topc, tops, topt = r[:9]
        term = re.sub(r"\s*\(\d+\)", "", topt)
        rows.append([sch, corp, f"{int(pl):,}", f"{int(fl):,}", f"{int(fb):,}",
                     topc, pct(float(tops)), term])
    rows.sort(key=lambda r: (r[1] != "corpus", r[0]))
    emit_rows("placement-stats", rows)
    n_flag90 = sum(1 for r in pc2 if r[1] == "corpus" and int(r[3]) / int(r[2]) > 0.9)
    V["n_flagged90"] = str(n_flag90)

    # ---- bias table ----
    def brow(name, corp, g, p):
        d = round(p["skill"], 4) - round(g["skill"], 4)
        return [name, corp, pct(g["coverage"]), pct(p["coverage"]),
                f3(g["skill"]), f3(p["skill"]), sdiff(d)]
    emit_rows("bias", [
        brow("arxiv", "corpus", g_arxiv, placed["arxiv"]),
        brow("msc", "corpus", g_msc, placed["msc"]),
        brow("jel", "corpus", g_jel, placed["jel"]),
        brow("lcc", "holdout", g_lcc, ph["lcc"]),
        brow("lcc-full", "holdout", g_lccfull, ph["lcc-full"]),
    ])

    # ---- navigation ----
    def nrow(j, label, corp):
        s = j["structure"]
        return [j["scheme"], label, corp, str(s["p50_depth"]), str(s["p95_depth"]),
                str(s["root_fanout"]), f1(s["nav_log_a0"]), f1(s["nav_log_a1"]),
                f1(s["nav_log_a2"]), f"{s['nav_scan']:.0f}"]
    nav = [nrow(g_arxiv, "gold", "corpus"), nrow(g_msc, "gold", "corpus"),
           nrow(g_jel, "gold", "corpus"), nrow(g_lcc, "gold", "holdout"),
           nrow(g_lccfull, "gold", "holdout")]
    for s in sorted(SCHEMES):
        nav.append(nrow(placed[s], "placed", "corpus"))
    for s in sorted(ph):
        nav.append(nrow(ph[s], "placed", "holdout"))
    emit_rows("navigation", nav)

    # ---- stopword fix: r1 -> r2 ----
    top1 = {(r[0], r[1]): (r[6], float(r[7])) for r in pc1}
    top2 = {(r[0], r[1]): (r[6], float(r[7])) for r in pc2}
    sw = []
    kinds = [(s, "corpus") for s in SCHEMES] + [(s, "holdout") for s in sorted(ph)]
    for s, corp in kinds:
        j1 = jload("r1", f"{s}-placed.json" if corp == "corpus" else f"{s}-placed-holdout.json")
        j2 = placed[s] if corp == "corpus" else ph[s]
        t1, t2 = top1[(s, corp)], top2[(s, corp)]
        sw.append([s, corp, f"{pct(t1[1])} {t1[0]}", f"{pct(t2[1])} {t2[0]}",
                   f"{pct(j1['coverage'])} → {pct(j2['coverage'])}",
                   f"{f3(j1['cost_norm'])} → {f3(j2['cost_norm'])}",
                   f"{f3(j1['skill'])} → {f3(j2['skill'])}",
                   sdiff(j2['skill'] - j1['skill'])])
        V[f"sw_{s}_{corp}_before"] = pct(t1[1])
        V[f"sw_{s}_{corp}_after"] = pct(t2[1])
        V[f"sw_{s}_{corp}_skill_before"] = f3(j1["skill"])
        V[f"sw_{s}_{corp}_skill_after"] = f3(j2["skill"])
    emit_rows("stopword", sw)
    a = [placed[s]["skill"] for s in SCHEMES]
    b = [jload("r1", f"{s}-placed.json")["skill"] for s in SCHEMES]
    V["sw_changed"] = str(sum(1 for x, y in zip(a, b) if abs(x - y) >= 0.0005))
    V["sw_kendall"] = f2(kendall_b(a, b))

    # ---- learned scheme (markdown tables of the learned results.md) ----
    lt = show("learned", "results.md")
    corp = md_table(lt, "## Corpus (n = 10,000)")
    held = md_table(lt, "## Held-out split (fitted on 80%, test on 20%, n = 2,000)")
    hold = md_table(lt, "## Holdout (n = 500, Open Library books, titles only)")

    def lrow(r, block):
        # scheme | placements | coverage | cost_norm | skill | J | nav | classes | depth | maxbr
        return None
    # tables have: scheme, placements, coverage, cost_norm, skill, J, nav, ...
    def shape(r):
        return [r[0], r[1], r[2], r[3], r[4], r[5], r[6]]
    keep_corpus = [("learned", "own, in-sample"), ("arxiv", "gold"),
                   ("learned", "shelfmark lexical@2"), ("openalex-topics", "shelfmark lexical@2"),
                   ("lcc-full", "shelfmark lexical@2")]
    out = []
    def pick(rows, block, keep):
        for r in rows:
            for k, plc in keep:
                if r[0] == k and r[1].startswith(plc):
                    cov, cost, skill, J, nav = r[2], r[3], r[4], r[5], r[6]
                    out.append([block, r[0], r[1], dec(cov, 3), dec(cost, 3),
                                dec(skill, 3), dec(J, 3), dec(nav, 1)])
    pick(corp, "corpus, n = 10,000", keep_corpus)
    pick(held, "held-out 20%, n = 2,000", [("learned (fit on the other 80%)", "own insertion"),
                                           ("learned (full fit)", "own, in-sample"),
                                           ("arxiv", "gold"), ("openalex-topics", "shelfmark lexical@2")])
    pick(hold, "book holdout, n = 500", [("learned", "own insertion"), ("lcc", "gold"),
                                         ("lcc-full", "gold"), ("lcc-full", "shelfmark lexical@2"),
                                         ("learned", "shelfmark lexical@2")])
    emit_rows("learned", out)
    # a few headline values read from the learned results.md
    avg = [r for r in corp if r[0].startswith("average linkage")][0]
    V["l_avg_cost"] = f"{float(avg[3]):.4f}"
    own = [r for r in corp if r[0] == "learned" and r[1].startswith("own")][0]
    V["l_own_cost"] = f"{float(own[3]):.4f}"
    V["l_own_skill"] = f"{float(own[4]):.4f}"
    V["l_own_J"] = f"{float(own[5]):.4f}"
    ho = [r for r in held if r[0].startswith("learned (fit on the other")][0]
    V["l_held_cost"] = f"{float(ho[3]):.4f}"
    fu = [r for r in held if r[0] == "learned (full fit)" and r[1].startswith("own")][0]
    V["l_full_on_test_cost"] = f"{float(fu[3]):.4f}"
    hb = [r for r in hold if r[0] == "learned" and r[1].startswith("own")][0]
    V["l_book_cost"] = f"{float(hb[3]):.4f}"
    V["l_book_skill"] = f"{float(hb[4]):.4f}"
    ll = [r for r in corp if r[0] == "learned" and r[1].startswith("shelfmark")][0]
    V["l_lex_cost"] = f"{float(ll[3]):.4f}"
    lh = [r for r in hold if r[0] == "learned" and r[1].startswith("shelfmark")][0]
    V["l_book_lex_cost"] = f"{float(lh[3]):.4f}"
    V["l_book_lex_cov"] = f"{float(lh[2]):.3f}"

    # ---- corpus facts, from the paper 1 table script (reads the corpus files) ----
    spec = importlib.util.spec_from_file_location(
        "p1_make_tables", ROOT / "paper/paper1/scripts/make_tables.py")
    p1 = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(p1)
    p1t, p1v = p1.build()
    for k in ["n_corpus", "n_holdout", "share_2026_ids", "share_physical_math_cs",
              "n_msc_rows", "n_acm_rows", "n_jel_rows", "holdout_with_text",
              "holdout_title_words", "holdout_p", "holdout_p_share",
              "holdout_letter_count", "holdout_other_top", "holdout_empty",
              "tau_corpus", "tau_holdout", "edges_corpus", "edges_holdout",
              "ref_seconds_corpus", "score_seconds_max", "arxiv_placed_top_share",
              "skipped_acm_note", "harness_commit", "classifier_commit",
              "graph_corpus_sha", "ref_corpus", "ref_holdout", "k", "model"]:
        V["c_" + k] = p1v[k]
    grp = []
    for line in p1t["corpus"].splitlines()[2:]:
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if cells[0].startswith("**"):
            continue
        grp.append((int(cells[1].replace(",", "")), cells[0], cells[1], cells[2]))
    grp.sort(key=lambda g: (-g[0], g[1]))
    parts = [f"{g[1]} {g[2]} ({g[3]})" for g in grp]
    V["c_groups"] = ", ".join(parts[:-1]) + " and " + parts[-1]

    # ---- learned scheme: build report, insertion and sweep ----
    lj = jload("learned", "results.json")
    bshape = lj["learned"]["build"]["shape"]
    V["l_classes"] = str(bshape["classes"])
    V["l_by_depth"] = ", ".join(str(bshape["classes_by_depth"][k])
                                for k in sorted(bshape["classes_by_depth"], key=int))
    V["l_fit_seconds"] = f"{sum(s['seconds'] for s in lj['learned']['build']['stages']):.1f}"
    ins = lj["insertion"]["holdout"]
    V["l_ins_new"] = str(ins["classes_after"] - ins["classes_before"])
    V["l_ins_stable"] = "no existing identifier" if ins["stable"] else "some identifiers"
    sw = lj["sweep"]
    V["l_sweep_cost_min"] = f"{min(s['dasgupta'] for s in sw):.4f}"
    V["l_sweep_cost_max"] = f"{max(s['dasgupta'] for s in sw):.4f}"
    V["l_sweep_classes_min"] = str(min(s["classes"] for s in sw))
    V["l_sweep_classes_max"] = str(max(s["classes"] for s in sw))
    V["l_sweep_depths"] = ", ".join(str(d) for d in sorted({s["max_depth"] for s in sw}))
    V["l_sweep_lam_min"] = f"{min(s['lambda'] for s in sw):g}"
    V["l_sweep_lam_max"] = f"{max(s['lambda'] for s in sw):g}"
    V["ref_holdout_seconds"] = f"{jload('r1', 'results.json')['graphs']['holdout']['reference']['seconds']:.1f}"

    # ---- shared results: validity, false-join, stability, books, semantic tier ----
    sys.path.insert(0, str(ROOT / "paper/common"))
    import extra_results
    xv, xt = extra_results.collect(ROOT)
    V.update(xv)

    def clean(c):
        return str(c).replace("`", "")

    def clean_head(c):
        return (str(c).replace("kappa", "κ").replace("rho", "ρ")
                .replace("tau", "τ"))

    for name, tab in xt.items():
        key = name.replace("_", "-")
        print(f"#let {key}-header = " + tup([clean_head(c) for c in tab["header"]]))
        print()
        emit_rows(key, [[clean(c) for c in r] for r in tab["rows"]])

    print("#let v = (")
    for k, val in V.items():
        print(f"  {k.replace('-', '_')}: {tstr(val)},")
    print(")")


def render():
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        main()
    return buf.getvalue()


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if generated.typ is stale")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    text = render()
    path = Path(a.out)
    if a.check:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            print(f"{path} is stale; run {Path(__file__).name}", file=sys.stderr)
            sys.exit(1)
        print(f"{path}: up to date")
    else:
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")
