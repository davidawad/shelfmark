//! The generated text: scheme JSON (one class per line, so a rebuild
//! diffs line by line) and SOURCES.md.

use std::fmt::Write;

use shelfmark_core::id::sha256_hex;
use shelfmark_core::scheme::SchemeDoc;

use crate::build::Stats;
use crate::sample;
use crate::sources::{Lock, DOWNLOAD_PAGE};

/// The scheme as JSON: header fields pretty-printed, then one class per
/// line, then a newline.
pub fn scheme_json(doc: &SchemeDoc) -> String {
    let mut head = doc.clone();
    head.classes.clear();
    let head = serde_json::to_string_pretty(&head).expect("a scheme serializes");
    let head = head
        .trim_end()
        .strip_suffix('}')
        .and_then(|h| h.trim_end().strip_suffix("\"classes\": []"))
        .expect("`classes` is the last field");
    let mut out = format!("{head}\"classes\": [\n");
    for (i, c) in doc.classes.iter().enumerate() {
        let sep = if i + 1 < doc.classes.len() { "," } else { "" };
        let line = serde_json::to_string(c).expect("a class serializes");
        let _ = writeln!(out, "    {line}{sep}");
    }
    out.push_str("  ]\n}\n");
    out
}

/// The input files, for the scheme's source description.
pub fn provenance(lock: &Lock) -> String {
    let files: Vec<String> = lock
        .sources
        .iter()
        .map(|l| format!("{} sha256 {}", l.file, l.sha256))
        .collect();
    format!("release {}; {}", lock.release, files.join("; "))
}

pub fn sources_md(
    lock: &Lock,
    s: &Stats,
    doc: &SchemeDoc,
    scheme: &str,
    sample_doc: &SchemeDoc,
    sample: &str,
) -> String {
    let mut o = String::new();
    let _ = write!(
        o,
        "# FAST scheme: sources\n\n\
         Generated by `schemes/fast` (`fast-scheme build`); do not edit by hand.\n\
         See README.md for the rules and the license.\n\n\
         ## Rebuild\n\n\
         ```sh\n\
         cd schemes/fast\n\
         cargo run --release -- fetch --cache /tmp/fast-sources   # network; verifies sha256 against the lock\n\
         cargo run --release -- build --cache /tmp/fast-sources   # offline, deterministic: out/fast.json, fast-sample.json, SOURCES.md\n\
         cargo run --release -- check --cache /tmp/fast-sources   # fails if any of the three is stale\n\
         ```\n\n\
         ## Sources\n\n\
         FAST release {release}, from the [FAST download page]({DOWNLOAD_PAGE}). \
         `fetch` tries the OCLC URL and then the pinned Internet Archive copy; \
         `build` refuses any cached file whose sha256 differs from `sources.lock.json`.\n\n\
         | file | member | fetched | bytes | sha256 |\n|---|---|---|---|---|\n",
        release = lock.release
    );
    for l in &lock.sources {
        let _ = writeln!(
            o,
            "| [{}]({}) ([mirror]({})) | `{}` | {} | {} | `{}` |",
            l.file, l.url, l.mirror, l.member, l.fetched, l.bytes, l.sha256
        );
    }
    let rows: [(&str, usize); 15] = [
        ("topical headings in the source", s.headings),
        ("deprecated (dropped as classes)", s.deprecated),
        (
            "other-facet headings named only by rdfs:label (not classes)",
            s.unlabelled,
        ),
        ("classes", s.classes),
        ("parent from skos:broader", s.parent_broader),
        ("parent by dropping subdivisions", s.parent_subdivision),
        ("top-level classes", s.top_level),
        (
            "classes with several live broader headings",
            s.multiple_broader,
        ),
        ("broader links refused (would cycle)", s.broader_cycles),
        (
            "broader links to deprecated or non-topical headings",
            s.broader_dangling,
        ),
        ("deepest level (top level is 0)", s.max_depth),
        ("alternate labels (`fast`)", s.alt_terms),
        ("LCSH links (`lcsh`)", s.lcsh_links),
        (
            "LCSH links without an LCSH label (FAST label used)",
            s.lcsh_unlabelled,
        ),
        (
            "deprecated labels on their replacements (`fast`)",
            s.replaced_terms,
        ),
    ];
    o.push_str("\n## What the build kept\n\n| | |\n|---|---|\n");
    for (k, v) in rows {
        let _ = writeln!(o, "| {k} | {v} |");
    }
    o.push_str(
        "\n## Outputs\n\nThe content hash is shelfmark's: sha256 over the document's canonical \
         JSON (`serde_json::to_vec` of the `SchemeDoc`), as `scheme compile` reports it.\n\n\
         | file | scheme | classes | bytes | file sha256 | content hash |\n|---|---|---|---|---|---|\n",
    );
    for (file, d, text) in [
        ("out/fast.json (not committed)", doc, scheme),
        ("fast-sample.json", sample_doc, sample),
    ] {
        let canonical = serde_json::to_vec(d).expect("a scheme serializes");
        let _ = writeln!(
            o,
            "| {file} | `{}` | {} | {} | `{}` | `s256:{}` |",
            d.id(),
            d.classes.len(),
            text.len(),
            sha256_hex(text.as_bytes()),
            sha256_hex(&canonical)
        );
    }
    let _ = writeln!(
        o,
        "\nThe sample is seeds {} with their ancestors and {} levels of descendants.",
        sample::SEEDS.join(", "),
        sample::DEPTH
    );
    o
}
